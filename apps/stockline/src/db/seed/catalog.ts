export type UnitDef = { key: string; th: string; en: string; symbol: string };

export type CatalogItem = {
  th: string;
  en: string;
  category: string;
  /** Base unit key. */
  unit: string;
  /** Pack units: [unit key, factor]. */
  packs?: [string, number][];
  /** Cost per base unit, baht (satang allowed via decimals). */
  cost: number;
  price?: number;
  /** Average base units going out per day. */
  rate: number;
  supplier: number;
};

